using System.Text;
using PackageCheck.Core;
using PackageCheck.Report.Model;
using static PackageCheck.Report.TextSafety;

namespace PackageCheck.Report;

/// <summary>
/// The markdown report (design 7.6): safe to paste into a PR comment. Every package-controlled string goes through
/// <see cref="TextSafety"/>; links are built only from https URLs. Layout is not versioned.
/// </summary>
public static class MarkdownReportWriter
{
    public static string Write(ScanReport r, bool verbose)
    {
        var md = new StringBuilder();
        md.AppendLine("# Umbraco Package Check").AppendLine();

        var summary = $"**Summary:** {ReportText.Summary(r.Summary)}.";
        if (r.Sites.Count == 1) summary += $" Target {Markdown(ReportText.Target(r.Sites[0].Target))}.";
        if (r.Summary.Incomplete) summary += " **Incomplete:** a required source failed or transitive packages were unavailable.";
        md.AppendLine(summary).AppendLine();

        var warnings = r.Warnings.Concat(r.Sites.SelectMany(s => s.Warnings)).ToList();
        if (warnings.Count > 0)
        {
            md.AppendLine("**Warnings**").AppendLine();
            foreach (var w in warnings) md.Append("- ").AppendLine(Markdown(w));
            md.AppendLine();
        }

        if (r.Sites.Count > 1) WriteMatrix(md, r.Sites, verbose);

        foreach (var site in r.Sites) WriteSite(md, site, r.Sites.Count > 1, verbose);

        md.AppendLine("---").AppendLine();
        md.Append("Generated by ").Append(Markdown($"{r.Tool.Name} {r.Tool.Version}"))
          .Append(". Code rules are not checked; see ").Append(Link("Umbraco17Check", ReportText.Umbraco17CheckUrl)).AppendLine(".");
        return md.ToString();
    }

    private static bool Shown(PackageReport p, bool verbose) => verbose || p.Verdict != "not-umbraco";

    private static void WriteMatrix(StringBuilder md, IReadOnlyList<SiteReport> sites, bool verbose)
    {
        md.AppendLine("## Sites").AppendLine();
        md.Append("| Package |");
        foreach (var s in sites) md.Append(' ').Append(Markdown(SiteName(s))).Append(" |");
        md.AppendLine().Append("|---|").AppendLine(string.Concat(Enumerable.Repeat("---|", sites.Count)));

        var ids = sites.SelectMany(s => s.Packages).Where(p => Shown(p, verbose))
            .GroupBy(p => p.Id, StringComparer.OrdinalIgnoreCase)
            .OrderBy(g => g.Min(p => ReportText.Rank(p.Verdict))).ThenBy(g => g.Key, StringComparer.OrdinalIgnoreCase);
        foreach (var g in ids)
        {
            md.Append("| ").Append(Markdown(g.First().Id)).Append(" |");
            foreach (var s in sites)
            {
                var cells = s.Packages.Where(p => string.Equals(p.Id, g.Key, StringComparison.OrdinalIgnoreCase))
                    .Select(p => Markdown($"{p.Current} {p.Verdict}{(p.Recommended is null ? "" : $" → {p.Recommended}")}"));
                md.Append(' ').Append(string.Join("<br>", cells)).Append(" |");
            }
            md.AppendLine();
        }
        md.AppendLine();
    }

    private static string SiteName(SiteReport s) =>
        Path.GetFileName(s.Path.TrimEnd('/', '\\')) is { Length: > 0 } name ? name : s.Path;

    private static void WriteSite(StringBuilder md, SiteReport site, bool multi, bool verbose)
    {
        var level = multi ? "###" : "##";
        if (multi)
        {
            md.Append("## ").AppendLine(Markdown(site.Path)).AppendLine();
            md.Append("Target ").Append(Markdown(ReportText.Target(site.Target))).AppendLine(".").AppendLine();
        }

        foreach (var (title, verdicts) in ReportText.Groups)
        {
            var rows = site.Packages.Where(p => verdicts.Contains(p.Verdict) && Shown(p, verbose)).ToList();
            if (rows.Count == 0) continue;
            md.Append(level).Append(' ').Append(title).Append(" (").Append(rows.Count).AppendLine(")").AppendLine();
            md.AppendLine("| Package | Current | Recommended | Confidence | Projects | Note |");
            md.AppendLine("|---|---|---|---|---|---|");
            foreach (var p in rows)
            {
                md.Append("| ").Append(Markdown(p.Id))
                  .Append(" | ").Append(Markdown(p.Current ?? ""))
                  .Append(" | ").Append(Markdown(p.Recommended ?? ""))
                  .Append(" | ").Append(p.Confidence ?? "n/a")
                  .Append(" | ").Append(Markdown(ReportText.Projects(p.Projects)))
                  .Append(" | ").Append(Note(p, site.Target))
                  .AppendLine(" |");
            }
            md.AppendLine();
        }

        var hidden = site.Packages.Count(p => !Shown(p, verbose));
        if (hidden > 0)
            md.Append(ReportText.Plural(hidden, "non-Umbraco package", "non-Umbraco packages")).AppendLine(" hidden (use --verbose to show).").AppendLine();

        var detailed = site.Packages.Where(p => Shown(p, verbose)).OrderBy(p => ReportText.Rank(p.Verdict)).ToList();
        if (detailed.Count == 0) return;
        md.Append(level).AppendLine(" Evidence").AppendLine();
        foreach (var p in detailed) WriteDetails(md, p);
    }

    private static string Note(PackageReport p, TargetReport target)
    {
        var parts = new List<string>();
        if (p.Reason is not null) parts.Add(Markdown(p.Reason));
        if (p.Verdict == "replaced" && p.Recommended is not null) parts.Add(Markdown($"replaced by {p.Recommended}"));
        if (p.Verdict == "no-release" && p.PrereleaseCompatible is not null)
            parts.Add(Markdown($"prerelease {p.PrereleaseCompatible} supports the target"));
        if (p.LatestStable is not null && !p.LatestStableClears && p.LatestStable != p.Recommended)
            parts.Add(Markdown($"latest {p.LatestStable} does not support {target.Resolved}"));
        if (p.Override is { } o)
        {
            var text = $"{Link(o.Label, o.Evidence)}: {Markdown(ReportText.Status(o.Status))}, computed: {Markdown(o.ComputedVerdict)}";
            if (o.Stale) text += ", stale (past review date)";
            parts.Add(text);
        }
        return string.Join("; ", parts);
    }

    private static void WriteDetails(StringBuilder md, PackageReport p)
    {
        md.Append("<details><summary>").Append(Html($"{p.Id} {p.Current}: {p.Verdict}")).AppendLine("</summary>").AppendLine();
        foreach (var e in p.Evidence)
            md.Append("- ").Append(Markdown($"{e.Check} {e.Result}, {e.Weight} ({e.Source}): {e.Detail}")).AppendLine();
        if (p.Override is { } o)
        {
            md.Append("- ").Append(Link(o.Label, o.Evidence)).Append(": ").Append(Markdown($"{ReportText.Status(o.Status)}: {o.Summary}"))
              .Append(Markdown($" (verified {o.VerifiedOn}, review by {o.ReviewBy}{(o.Stale ? ", stale" : "")})")).AppendLine();
            if (o.Replacement is not null) md.Append("- ").AppendLine(Markdown($"Suggested replacement: {o.Replacement}"));
        }
        if (p.Marketplace is { } m)
        {
            md.Append("- ").Append(Link("Marketplace listing", m.Url));
            if (m.Retired) md.Append(Markdown(" (retired)"));
            if (m.Alternate is not null) md.Append(Markdown($", alternate {m.Alternate}"));
            md.AppendLine();
        }
        md.AppendLine().AppendLine("</details>").AppendLine();
    }
}
